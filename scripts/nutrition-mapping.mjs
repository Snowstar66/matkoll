//   gronsak fruit/veg/mushrooms/herbs-as-vegetables/roots except potato, baljvaxt pulses (incl. tofu, soy),
//   fisk fish and shellfish, rott_kott beef/pork/lamb/game/charcuterie, fagel poultry, agg eggs, mejeri dairy,
//   fullkorn whole grain, raffinerad white flour/rice/pasta/bread/potato, fett fats and oils,
//   socker sugar and sweet things, ovrigt other (nuts, sauces ...), ej_raknad not counted.

